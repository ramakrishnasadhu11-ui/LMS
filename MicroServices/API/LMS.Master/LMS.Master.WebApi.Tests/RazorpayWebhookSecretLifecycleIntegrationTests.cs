    public class RazorpayWebhookSecretLifecycleIntegrationTests : IClassFixture<RazorpaySqlServerFixture>
    {
        private readonly RazorpaySqlServerFixture _fixture;

        public RazorpayWebhookSecretLifecycleIntegrationTests(RazorpaySqlServerFixture fixture)
        {
            _fixture = fixture;
        }

        [Fact]
        public async Task Save_WithoutWebhookSecret_GeneratesSecret()
        {
            EnsureFixtureReady();
            var (tenant, store) = NewScope();

            await using var context = _fixture.CreateDbContext();
            var service = _fixture.CreateService(context);

            var saveResult = await service.SaveTenantIntegrationSettings(BuildRazorpayDto(tenant, store));
            Assert.Equal(HttpStatusCode.OK, saveResult.StatusCode);

            var record = await context.TenantIntegrationSettings
                .AsNoTracking()
                .SingleAsync(x => x.TenantName == tenant && x.StoreCode == store && x.Category == IntegrationConstants.Category.Payments && x.ProviderKey == "razorpay");

            var payload = ParsePayload(record.EncryptedSettingsJson, _fixture.EncryptionKey);
            var webhookSecret = GetSecret(payload, "WebhookSecret");

            Assert.False(string.IsNullOrWhiteSpace(webhookSecret));
            Assert.Equal("true", GetSecret(payload, "__els_webhook_secret_managed"), ignoreCase: true);
            Assert.Equal("false", GetSecret(payload, "__els_webhook_secret_revealed"), ignoreCase: true);
        }

        [Fact]
        public async Task Save_UnrelatedUpdate_PreservesExistingWebhookSecret()
        {
            EnsureFixtureReady();
            var (tenant, store) = NewScope();

            await using var context = _fixture.CreateDbContext();
            var service = _fixture.CreateService(context);

            await service.SaveTenantIntegrationSettings(BuildRazorpayDto(tenant, store));
            var initialRecord = await context.TenantIntegrationSettings
                .AsNoTracking()
                .SingleAsync(x => x.TenantName == tenant && x.StoreCode == store && x.Category == IntegrationConstants.Category.Payments && x.ProviderKey == "razorpay");
            var initialSecret = GetSecret(ParsePayload(initialRecord.EncryptedSettingsJson, _fixture.EncryptionKey), "WebhookSecret");

            var updateDto = BuildRazorpayDto(tenant, store);
            updateDto.PublicSettings["DisplayName"] = "Updated name";
            var updateResult = await service.SaveTenantIntegrationSettings(updateDto);
            Assert.Equal(HttpStatusCode.OK, updateResult.StatusCode);

            var updatedRecord = await context.TenantIntegrationSettings
                .AsNoTracking()
                .SingleAsync(x => x.TenantName == tenant && x.StoreCode == store && x.Category == IntegrationConstants.Category.Payments && x.ProviderKey == "razorpay");
            var updatedSecret = GetSecret(ParsePayload(updatedRecord.EncryptedSettingsJson, _fixture.EncryptionKey), "WebhookSecret");

            Assert.Equal(initialSecret, updatedSecret);
        }

        [Fact]
        public async Task ManualWebhookSecret_CannotBeRevealed()
        {
            EnsureFixtureReady();
            var (tenant, store) = NewScope();

            await using var context = _fixture.CreateDbContext();
            var service = _fixture.CreateService(context);

            var dto = BuildRazorpayDto(tenant, store);
            dto.SecretSettings["WebhookSecret"] = "manual-webhook-secret-value";
            var saveResult = await service.SaveTenantIntegrationSettings(dto);
            Assert.Equal(HttpStatusCode.OK, saveResult.StatusCode);

            var revealResult = await service.RevealTenantIntegrationWebhookSecretOnce(tenant, store, IntegrationConstants.Category.Payments, "razorpay");
            Assert.Equal(HttpStatusCode.BadRequest, revealResult.StatusCode);

            var response = Assert.IsType<CustomerIOResponse>(revealResult.ResultSet);
            Assert.Contains("not generated by ELS", response.Message, StringComparison.OrdinalIgnoreCase);
        }

        [Fact]
        public async Task ElsGeneratedSecret_CanBeRevealedExactlyOnce_AndSecondRevealRejected()
        {
            EnsureFixtureReady();
            var (tenant, store) = NewScope();

            await using var context = _fixture.CreateDbContext();
            var service = _fixture.CreateService(context);

            await service.SaveTenantIntegrationSettings(BuildRazorpayDto(tenant, store));

            var firstReveal = await service.RevealTenantIntegrationWebhookSecretOnce(tenant, store, IntegrationConstants.Category.Payments, "razorpay");
            Assert.Equal(HttpStatusCode.OK, firstReveal.StatusCode);
            var firstPayload = Assert.IsType<TenantIntegrationRevealWebhookSecretResponseDto>(firstReveal.ResultSet);
            Assert.False(string.IsNullOrWhiteSpace(firstPayload.WebhookSecret));

            var secondReveal = await service.RevealTenantIntegrationWebhookSecretOnce(tenant, store, IntegrationConstants.Category.Payments, "razorpay");
            Assert.Equal(HttpStatusCode.Conflict, secondReveal.StatusCode);
        }

        [Fact]
        public async Task Rotation_GeneratesDifferentSecret_AndDisablesIntegration()
        {
            EnsureFixtureReady();
            var (tenant, store) = NewScope();

            await using var context = _fixture.CreateDbContext();
            var service = _fixture.CreateService(context);

            await service.SaveTenantIntegrationSettings(BuildRazorpayDto(tenant, store));
            var firstReveal = await service.RevealTenantIntegrationWebhookSecretOnce(tenant, store, IntegrationConstants.Category.Payments, "razorpay");
            var oldSecret = Assert.IsType<TenantIntegrationRevealWebhookSecretResponseDto>(firstReveal.ResultSet).WebhookSecret;

            var record = await context.TenantIntegrationSettings.SingleAsync(x => x.TenantName == tenant && x.StoreCode == store && x.Category == IntegrationConstants.Category.Payments && x.ProviderKey == "razorpay");
            record.IsEnabled = true;
            await context.SaveChangesAsync();

            var rotateResult = await service.RotateTenantIntegrationWebhookSecret(tenant, store, IntegrationConstants.Category.Payments, "razorpay");
            Assert.Equal(HttpStatusCode.OK, rotateResult.StatusCode);

            var rotatedRecord = await context.TenantIntegrationSettings
                .AsNoTracking()
                .SingleAsync(x => x.TenantName == tenant && x.StoreCode == store && x.Category == IntegrationConstants.Category.Payments && x.ProviderKey == "razorpay");
            Assert.False(rotatedRecord.IsEnabled);

            var postRotateReveal = await service.RevealTenantIntegrationWebhookSecretOnce(tenant, store, IntegrationConstants.Category.Payments, "razorpay");
            Assert.Equal(HttpStatusCode.OK, postRotateReveal.StatusCode);
            var newSecret = Assert.IsType<TenantIntegrationRevealWebhookSecretResponseDto>(postRotateReveal.ResultSet).WebhookSecret;

            Assert.NotEqual(oldSecret, newSecret);
        }

        [Fact]
        public async Task ConcurrentReveal_OnlyOneSucceeds()
        {
            EnsureFixtureReady();
            var (tenant, store) = NewScope();

            await using (var setupContext = _fixture.CreateDbContext())
            {
                var setupService = _fixture.CreateService(setupContext);
                await setupService.SaveTenantIntegrationSettings(BuildRazorpayDto(tenant, store));
            }

            var gate = new ManualResetEventSlim(false);

            async Task<HttpStatusCode> RunRevealAsync()
            {
                await using var context = _fixture.CreateDbContext();
                var service = _fixture.CreateService(context);
                gate.Wait();
                var result = await service.RevealTenantIntegrationWebhookSecretOnce(tenant, store, IntegrationConstants.Category.Payments, "razorpay");
                return result.StatusCode;
            }

            var t1 = Task.Run(RunRevealAsync);
            var t2 = Task.Run(RunRevealAsync);
            gate.Set();

            var statuses = await Task.WhenAll(t1, t2);
            Assert.Equal(1, statuses.Count(x => x == HttpStatusCode.OK));
            Assert.Equal(2, statuses.Length);
        }

        private static TenantIntegrationSettingsDto BuildRazorpayDto(string tenant, string store)
        {
            return new TenantIntegrationSettingsDto
            {
                TenantName = tenant,
                StoreCode = store,
                Category = IntegrationConstants.Category.Payments,
                ProviderKey = "razorpay",
                ProviderDisplayName = "Razorpay",
                IsTestMode = true,
                PublicSettings = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
                {
                    ["Provider"] = "Razorpay"
                },
                SecretSettings = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
                {
                    ["TestKeyId"] = "rzp_test_key_id",
                    ["TestKeySecret"] = "rzp_test_key_secret"
                }
            };
        }

        private void EnsureFixtureReady()
        {
            Assert.True(_fixture.IsAvailable, _fixture.UnavailableReason ?? "SQL Server test fixture unavailable.");
        }

        private static (string Tenant, string Store) NewScope()
            => ($"tenant-{Guid.NewGuid():N}", $"store-{Guid.NewGuid():N}");

        private static JsonElement ParsePayload(string encryptedPayload, string keyMaterial)
        {
            var decrypted = DecryptString(encryptedPayload, keyMaterial);
            using var document = JsonDocument.Parse(decrypted);
            return document.RootElement.Clone();
        }

        private static string GetSecret(JsonElement payload, string key)
        {
            if (!payload.TryGetProperty("Secret", out var secret) || secret.ValueKind != JsonValueKind.Object)
            {
                return null;
            }

            foreach (var property in secret.EnumerateObject())
            {
                if (string.Equals(property.Name, key, StringComparison.OrdinalIgnoreCase))
                {
                    return property.Value.GetString();
                }
            }

            return null;
        }

        private static string DecryptString(string encryptedText, string keyMaterial)
        {
            if (string.IsNullOrWhiteSpace(encryptedText) || !encryptedText.Contains(':'))
            {
                return string.Empty;
            }

            var parts = encryptedText.Split(':');
            var iv = Convert.FromBase64String(parts[0]);
            var cipherBytes = Convert.FromBase64String(parts[1]);

            using var sha256 = SHA256.Create();
            var key = sha256.ComputeHash(Encoding.UTF8.GetBytes(string.IsNullOrWhiteSpace(keyMaterial)
                ? "LMS_Master_Default_Integration_Key"
                : keyMaterial));

            using var aes = Aes.Create();
            aes.Key = key;
            aes.IV = iv;
            aes.Mode = CipherMode.CBC;
            aes.Padding = PaddingMode.PKCS7;

            var decryptor = aes.CreateDecryptor(aes.Key, aes.IV);
            var plainBytes = decryptor.TransformFinalBlock(cipherBytes, 0, cipherBytes.Length);
            return Encoding.UTF8.GetString(plainBytes);
        }
    }

    public sealed class RazorpaySqlServerFixture : IAsyncLifetime
    {
        private readonly string _databaseName = $"LmsMasterWebhookTests_{Guid.NewGuid():N}";
        private DbContextOptions<MasterDbContext> _dbOptions;

        public bool IsAvailable { get; private set; }
        public string UnavailableReason { get; private set; }
        public string EncryptionKey { get; } = "LMS_Master_Test_Integration_Key";

        public string ConnectionString =>
            $"Server=(localdb)\\MSSQLLocalDB;Integrated Security=true;Initial Catalog={_databaseName};TrustServerCertificate=True;MultipleActiveResultSets=True";

        public Task InitializeAsync()
        {
            try
            {
                _dbOptions = new DbContextOptionsBuilder<MasterDbContext>()
                    .UseSqlServer(ConnectionString)
                    .Options;

                using var db = new MasterDbContext(_dbOptions);
                db.Database.EnsureCreated();
                IsAvailable = true;
            }
            catch (Exception ex)
            {
                IsAvailable = false;
                UnavailableReason = $"SQL Server LocalDB unavailable for integration tests: {ex.GetType().Name}";
            }

            return Task.CompletedTask;
        }

        public Task DisposeAsync()
        {
            if (!IsAvailable)
            {
                return Task.CompletedTask;
            }

            try
            {
                using var db = new MasterDbContext(_dbOptions);
                db.Database.EnsureDeleted();
            }
            catch
            {
            }

            return Task.CompletedTask;
        }

        public MasterDbContext CreateDbContext()
        {
            return new MasterDbContext(_dbOptions);
        }

        public Customerservice CreateService(MasterDbContext context)
        {
            var mapperConfig = new MapperConfiguration(cfg =>
            {
                cfg.CreateMap<TenantIntegrationSettingsEntity, TenantIntegrationSettingsDto>();
            });

            var configuration = new ConfigurationBuilder()
                .AddInMemoryCollection(new Dictionary<string, string>
                {
                    ["IntegrationSettings:EncryptionKey"] = EncryptionKey,
                    ["IntegrationSettings:MasterApiPublicBaseUrl"] = "https://master-api.test.local"
                })
                .Build();

            return new Customerservice(
                mapperConfig.CreateMapper(),
                context,
                configuration,
                NullLogger<Customerservice>.Instance);
        }
    }
